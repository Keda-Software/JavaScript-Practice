// Display text in the console
console.log("Hello, JavaScript!");

// Display numbers
console.log(100);
console.log(20 + 30);

// Display multiple values
console.log("Name:", "Keda");
console.log("Age:", 20);

// Display calculations
console.log(10 + 5);
console.log(10 - 5);
console.log(10 * 5);
console.log(10 / 5);
console.log(10 % 3);

// Display true or false
console.log(10 > 5);
console.log(10 < 5);

// Display a message using alert
// alert("Welcome to JavaScript!");

// Display a message in the browser
// document.write("Learning JavaScript");

// Use console.error for errors
console.error("Example error message");

// Use console.warn for warnings
console.warn("Example warning");

// Group console output
console.group("Student Information");
console.log("Name: Abel");
console.log("Grade: 90");
console.groupEnd();

// Display a table
console.table([
  { name: "Abel", grade: 90 },
  { name: "Sara", grade: 85 }
]);

console.log("End of program");

